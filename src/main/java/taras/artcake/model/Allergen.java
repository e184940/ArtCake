package taras.artcake.model;

public class Allergen {
    private Long id;

    private String name;

    public Allergen() {
    }

    public Long getId() {
        return id;
    }

    public void setId(Long id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

}

